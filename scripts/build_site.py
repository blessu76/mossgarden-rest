def breadcrumb_html(items):
    return '<nav class="crumbs" aria-label="breadcrumb">%s</nav>' % " › ".join(
        '<a href="%s">%s</a>' % (esc(h), esc(l)) if h else "<span>%s</span>" % esc(l) for h, l in items)


def breadcrumb_ld(items):
    return {"@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": i + 1, "name": l, **({"item": url(h)} if h else {})} for i, (h, l) in enumerate(items)]}


def website_ld(lang):
    return {"@type": "WebSite", "@id": SITE + "/#website", "url": SITE + "/", "name": NAME, "inLanguage": lang,
            "publisher": kit.org_ref()}


def game_ld(lang, ctx):
    return {"@type": "VideoGame", "@id": SITE + "/#game", "name": NAME, "url": url(path_home(lang)),
            "description": ctx.t(lang, "home_desc"), "inLanguage": lang, "genre": [GAME["genre"]],
            "applicationCategory": "GameApplication", "gamePlatform": GAME["platforms"], "playMode": "SinglePlayer",
            "image": SITE + OG_IMAGE, "creator": dict(kit.ORG), "publisher": kit.org_ref()}


# ---------------------------------------------------------------- page builders
def build_home(ctx, lang):
    t = lambda k: ctx.t(lang, k)  # noqa: E731
    cards = "".join('<article class="card feat"><h3>%s</h3><p>%s</p></article>' % (esc(t("card%d_h" % i)), esc(t("card%d_p" % i))) for i in (1, 2, 3))
    facts = "".join("<li>%s</li>" % esc(t("fact%d" % i)) for i in range(1, 6))
    body = ('<section class="hero"><div class="hero-text"><p class="badge">%s</p><h1>%s</h1><p class="lead">%s</p>'
            '<p class="actions"><a class="btn" href="%s">%s</a></p>'
            '<div class="stores" aria-label="%s"><span class="store"><b>%s</b></span></div><p class="note">%s</p></div>'
            '<img class="hero-art" src="/assets/hero.svg?v=%s" alt="" width="640" height="720" fetchpriority="high"></section>'
            '<section class="section"><div class="grid three">%s</div></section>'
            '<section class="section shots"><h2>%s</h2><figure class="shot-ph"><figcaption>%s</figcaption></figure></section>'
            '<section class="section facts"><h2>%s</h2><ul>%s</ul></section>') % (
        esc(t("status_badge")), esc(t("hero_h1")), esc(t("hero_lead")), esc(path_page(lang, "contact")), esc(t("contact_cta")),
        esc(t("store_h")), esc(t("store_soon")),
        esc(t("hero_note")), ASSET_V, cards, esc(t("shots_h")), esc(t("shots_note")), esc(t("facts_h")), facts)
    alt = {l: path_home(l) for l in ctx.langs}
    graph = [kit.ORG, website_ld(lang), game_ld(lang, ctx)]
    return path_home(lang), render(ctx, lang, path=path_home(lang), title=t("home_title"), desc=t("home_desc"), body=body,
                                   graph=graph, alt=alt, nav="home")


def build_page(ctx, lang, slug):
    meta, md = ctx.pages[(lang, slug)]
    t = lambda k: ctx.t(lang, k)  # noqa: E731
    crumbs = [(path_home(lang), t("crumb_home")), (None, meta["title"])]
    body = '%s<article class="prose"><h1>%s</h1>%s</article>' % (
        breadcrumb_html(crumbs), esc(meta["title"]), markdown(ctx.sub(md)))
    page_ld = {"@type": "ContactPage" if slug == "contact" else "WebPage", "@id": url(path_page(lang, slug)) + "#page",
               "url": url(path_page(lang, slug)), "name": meta["title"], "description": meta["description"], "inLanguage": lang,
               "isPartOf": {"@id": SITE + "/#website"}}
    graph = [kit.ORG, website_ld(lang), page_ld, breadcrumb_ld(crumbs)]
    alt = {l: path_page(l, slug) for l in ctx.langs if (l, slug) in ctx.pages}
    return path_page(lang, slug), render(ctx, lang, path=path_page(lang, slug), title="%s — %s" % (meta["title"], brand_name(lang)),
                                         desc=meta["description"], body=body, graph=graph, alt=alt, nav=slug)


def build_404(ctx):
    lang = "en"
    body = '<h1>404</h1><p class="lead">%s</p><p><a class="btn" href="/">%s</a></p>' % (esc(ctx.t(lang, "not_found")), esc(ctx.t(lang, "nav_home")))
    return render(ctx, lang, path="/404.html", title="404 — %s" % NAME, desc="Page not found.", body=body,
                  graph=[kit.ORG, website_ld(lang)], alt={"en": "/"}, noindex=True, hreflang=False)


# ---------------------------------------------------------------- site files
def sitemap_entries(ctx):
    """[(path, lastmod, {lang: path})]"""
    ents = []
    for l in ctx.langs:
        ents.append((path_home(l), PAGES_UPDATED, {x: path_home(x) for x in ctx.langs}))
        for slug in PAGE_SLUGS:
            if (l, slug) in ctx.pages:
                ents.append((path_page(l, slug), PAGES_UPDATED, {x: path_page(x, slug) for x in ctx.langs if (x, slug) in ctx.pages}))
    return ents


def build_sitemap(ctx):
    rows = ['<?xml version="1.0" encoding="UTF-8"?>', "<!-- %s -->" % GEN_MARK,
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">']
    for pth, lm, alts in sitemap_entries(ctx):
        rows.append("<url><loc>%s</loc><lastmod>%s</lastmod>" % (esc(url(pth)), lm))
        if len(alts) > 1:
            rows += ['<xhtml:link rel="alternate" hreflang="%s" href="%s"/>' % (kl.hreflang(l), esc(url(ap))) for l, ap in alts.items()]
            rows.append('<xhtml:link rel="alternate" hreflang="x-default" href="%s"/>' % esc(url(alts.get("en", next(iter(alts.values()))))))
        rows.append("</url>")
    rows.append("</urlset>")
    return "\n".join(rows) + "\n"


def build_robots():
    rows = ["# %s" % GEN_MARK, "User-agent: *", "Allow: /", ""]
    for b in BOTS:
        rows += ["User-agent: %s" % b, "Allow: /", ""]
    rows += ["Sitemap: %s/sitemap.xml" % SITE, ""]
    return "\n".join(rows)


def build_llms(ctx):
    en = ctx.i18n["en"]
    rows = ["# %s" % NAME, "", "> %s" % en["home_desc"], "",
            "%s is a single-player idle game by ipe() (https://ipe.rest/). It is in development and has NOT been released: "
            "no store page, release date or final price exists yet. This site is the game's home page." % NAME, "",
            "## Key facts", ""]
    rows += ["- %s" % en["fact%d" % i] for i in range(1, 6)]
    rows += ["", "## Pages", "", "- [Home](%s/): %s" % (SITE, en["hero_lead"])]
    for slug in PAGE_SLUGS:
        rows.append("- [%s](%s%s)" % (ctx.pages[("en", slug)][0]["title"], SITE, path_page("en", slug)))
    rows += ["", "## Languages", "", "The site is available in 12 languages: %s. English and Korean are written by hand; the others are machine-translated drafts. "
             "Legal pages (privacy) exist only in English and Korean; other languages link to them. "
             "Each language lives under /<code>/ (English at the root)." % ", ".join(kl.NAMES[l] for l in ctx.langs), "",
             "## Contact and operator", "", "%s — %s" % (OPERATOR, EMAIL), ""]
    return "\n".join(rows)


# ---------------------------------------------------------------- orchestration
def make_ctx(root, require_all=False):
    root = Path(root)
    i18n, errs = load_i18n(root)
    pages, e2 = load_pages(root)
    errs += e2
    langs = [l for l in LANGS if l in i18n and all((l, s) in pages for s in PAGE_SLUGS)]
    if not all(m in langs for m in MAIN_LANGS):
        errs.append("%s must be complete (i18n + %s)" % (" and ".join(MAIN_LANGS), " + ".join(PAGE_SLUGS)))
    for l in LANGS:
        if l not in langs and require_all:
            errs.append("language %s is incomplete (needs i18n/%s.json and pages/%s/{%s}.md)" % (l, l, l, ",".join(PAGE_SLUGS)))
    cname = root / "CNAME"
    if cname.is_file() and cname.read_text(encoding="utf-8").strip() != DOMAIN:
        errs.append("CNAME (%s) does not match games.json domain (%s)" % (cname.read_text(encoding="utf-8").strip(), DOMAIN))
    return Ctx(root, i18n, pages, langs), errs


def build_all(ctx):
    """-> {relative file path: text}"""
    files = {}

    def put(path, text):
        files[path.lstrip("/") + "index.html" if path.endswith("/") else path.lstrip("/")] = text

    for l in ctx.langs:
        put(*build_home(ctx, l))
        for slug in PAGE_SLUGS:
            put(*build_page(ctx, l, slug))
    files["404.html"] = build_404(ctx)
    files["sitemap.xml"] = build_sitemap(ctx)
    files["robots.txt"] = build_robots()
    files["llms.txt"] = build_llms(ctx)
    return files


def clean(root):
    root = Path(root)
    for name in list(PAGE_SLUGS) + [l for l in LANGS if l != "en"]:
        d = root / name
        if d.is_dir():
            shutil.rmtree(d)
    for name in ("index.html", "404.html", "sitemap.xml", "robots.txt", "llms.txt"):
        f = root / name
        if f.is_file():
            f.unlink()


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(ROOT))
    ap.add_argument("--check", action="store_true", help="validate sources only")
    ap.add_argument("--require-all", action="store_true", help="fail unless every language in games.json is complete")
    a = ap.parse_args(argv)
    root = Path(a.root).resolve()
    ctx, errs = make_ctx(root, require_all=a.require_all)
    if errs:
        print("build_site: %d problem(s)\n  %s" % (len(errs), "\n  ".join(errs)), file=sys.stderr)
        return 1
    files = build_all(ctx)
    if a.check:
        print("build_site: sources OK — %d language(s), %d file(s) would be written" % (len(ctx.langs), len(files)))
        return 0
    clean(root)
    for rel, text in files.items():
        f = root / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text, encoding="utf-8")
    print("build_site: wrote %d file(s) — %d language(s)" % (len(files), len(ctx.langs)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
